//! **dreamkernel**：把「一个神经网络结构长什么样」变成可声明、可校验、可导出的东西。
//!
//! 这个 crate 只包含**框架层**——形状（拓扑）、对齐（映射）、声明与校验的机制。
//! 具体是哪个脑（哪些区、哪些通路、什么动力学）属于**实现层**，不在本 crate 里。
//!
//! 设计原则：
//! * **零依赖**：只有几何/映射/校验，不拖张量、GPU、文件格式。
//! * **不猜语义**：`Topo` 只说"形状"，`Map` 只说"两端怎么对齐"；
//!   什么区叫什么、接哪条通路，是实现层的事。
//! * **能不崩就不崩**：校验返回**全部**问题，而不是第一个就 panic。
//!
//! 两层分工：本 crate 只出"机制"；具体是哪个脑（哪些区、哪条通路）由使用它的 crate 提供。

pub mod assembly;
pub mod core;
pub mod link;
pub mod num;
pub mod sim;
